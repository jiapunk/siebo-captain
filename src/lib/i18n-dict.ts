export const DICTS: Record<Locale, Dict> = { zh, cn, en, ja };

export function translate(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const raw = DICTS[locale]?.[key] ?? DICTS.zh[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k) =>
    vars[k] !== undefined ? String(vars[k]) : `{${k}}`,
  );
}

export function detectLocale(): Locale {
  if (typeof document !== "undefined") {
    const m = document.cookie.match(/(?:^|;\s*)sc_lang=(zh|cn|en|ja)/);
    if (m) return m[1] as Locale;
  }
  if (typeof navigator !== "undefined") {
    const nav = navigator.language.toLowerCase();
    if (nav.startsWith("ja")) return "ja";
    if (nav.startsWith("en")) return "en";
    if (nav.startsWith("zh")) {
      if (/zh-(tw|hk|mo|hant)/.test(nav)) return "zh";
      return "cn";
    }
  }
  return "zh";
}
